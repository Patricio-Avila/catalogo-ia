-- 0001: esquemas, extensiones, configuración de verticales y tabla producto.
-- CLAUDE.md §4 (esquema híbrido), §7.2 puntos 6, 7, 11, 14 y 18.
--
-- Tres esquemas con responsabilidades distintas:
--   catalogo  lo que el agente puede ver, siempre a través de funciones
--   interno   márgenes y verdad del generador: ningún permiso para el agente (G3)
--   servicio  caché exacta: solo por funciones SECURITY DEFINER

create extension if not exists pg_trgm with schema extensions;

create schema if not exists catalogo;
create schema if not exists interno;
create schema if not exists servicio;

comment on schema catalogo is 'Catálogo de productos con atributos heterogéneos; el agente accede solo por funciones';
comment on schema interno is 'Datos internos (márgenes, verdad del generador, pares trampa); sin permisos para el agente';
comment on schema servicio is 'Caché exacta de interpretaciones; sin permisos directos para el agente';

-- Una vertical es configuración, no código (ADR-0005): agregar una es insertar aquí y cargar productos.
create table catalogo.vertical (
  dominio              text primary key check (dominio ~ '^[a-z][a-z0-9_]*$'),
  nombre               text not null,
  texto_ayuda          text not null default '',
  aviso                text,
  atributos_destacados text[] not null default '{}',
  orden                smallint not null default 0,
  -- cambia en cada refresco del diccionario; forma parte de la clave de la caché (RF-08)
  version_diccionario  text not null default '0',
  actualizado_en       timestamptz not null default now()
);
comment on table catalogo.vertical is 'Verticales (dominios) del catálogo: farmacia, llantas, belleza. Configuración que lee el cliente.';
comment on column catalogo.vertical.aviso is 'Texto que el cliente muestra siempre en la vertical (por ejemplo, en farmacia: solo búsqueda de catálogo)';

create table catalogo.categoria (
  dominio   text not null references catalogo.vertical on delete cascade,
  categoria text not null check (categoria ~ '^[a-z][a-z0-9_]*$'),
  nombre    text not null,
  orden     smallint not null default 0,
  primary key (dominio, categoria)
);
comment on table catalogo.categoria is 'Categorías por vertical. La categoría es el contexto de primer nivel: la comparación solo ocurre dentro de la misma categoría.';

-- Esquema híbrido: columnas fijas para lo común y JSONB para lo variable.
-- Dato faltante = clave ausente en atributos; nunca un valor.
create table catalogo.producto (
  id          bigint generated by default as identity primary key,
  dominio     text not null,
  categoria   text not null,
  nombre      text not null,
  marca       text not null,
  precio      numeric(10, 2) not null check (precio > 0),
  descripcion text not null,
  atributos   jsonb not null default '{}'::jsonb check (jsonb_typeof(atributos) = 'object'),
  foreign key (dominio, categoria) references catalogo.categoria
);
comment on table catalogo.producto is 'Productos del catálogo sintético. Columnas fijas más atributos variables en JSONB.';
comment on column catalogo.producto.atributos is 'Atributos técnicos y de contexto. Un atributo sin dato no está como clave.';
comment on column catalogo.producto.descripcion is 'Texto por plantilla desde los atributos completos; puede mencionar atributos que la columna atributos no tiene.';

-- Índices. jsonb_path_ops solo acelera @>; las igualdades del objeto de filtros se
-- traducen a contención para usarlo (C1). La clase de operadores definitiva se
-- decide midiendo en el documento 2 (§7.2.10).
create index producto_atributos_idx on catalogo.producto using gin (atributos jsonb_path_ops);
create index producto_dominio_categoria_idx on catalogo.producto (dominio, categoria);
-- Búsqueda tolerante por nombre y descripción (fase B, RF-09).
create index producto_nombre_trgm_idx on catalogo.producto using gin (nombre extensions.gin_trgm_ops);
create index producto_descripcion_trgm_idx on catalogo.producto using gin (descripcion extensions.gin_trgm_ops);

-- Verdad del generador: atributos completos antes de borrar los que caen fuera de
-- la cobertura. La diferencia con producto.atributos mide los faltantes (D-02).
create table interno.producto_verdad (
  producto_id bigint primary key references catalogo.producto on delete cascade,
  atributos   jsonb not null
);
comment on table interno.producto_verdad is 'Atributos completos de cada producto antes de aplicar la cobertura; sirve para medir faltantes y habilitar D-02.';

-- Pares trampa: mismos atributos técnicos, distinto uso o riesgo. El comparador debe negarse o acotar.
create table interno.par_trampa (
  id         serial primary key,
  dominio    text not null references catalogo.vertical,
  producto_a bigint not null references catalogo.producto on delete cascade,
  producto_b bigint not null references catalogo.producto on delete cascade,
  motivo     text not null,
  check (producto_a <> producto_b)
);

-- Información interna de ejemplo que el agente nunca debe ver (RNF-02).
create table interno.margen (
  producto_id bigint primary key references catalogo.producto on delete cascade,
  margen_pct  numeric(5, 2) not null check (margen_pct between 0 and 100)
);
